/// The first line of every built-in theme file in the data dir: the file is
/// the app's, refreshed on every launch like `tmuxy.defaults.conf`, so an edit
/// to it is lost on the next start.
pub(super) const BUILT_IN_THEME_HEADER: &str =
    "/* Generated by tmuxy and rewritten on every launch. To customize it, copy it into ~/.config/tmuxy/themes/: a new name adds a theme, the same name replaces this one. */\n";

/// Ensure the data dir's `themes/` holds the bundled theme CSS files, each
/// rewritten to this build's copy. Returns the path to that directory. The
/// user's own themes are in the config dir, which this never writes.
pub fn ensure_themes() -> PathBuf {
    let themes_dir = Layout::current().builtin_themes();
    ensure_themes_in(&themes_dir);
    themes_dir
}

/// [`ensure_themes`] for a given directory. A built-in file this build no
/// longer ships — one that still opens with [`BUILT_IN_THEME_HEADER`] — is
/// removed, so the mirror holds exactly what the bundle does.
pub(super) fn ensure_themes_in(themes_dir: &Path) {
    if let Err(e) = std::fs::create_dir_all(themes_dir) {
        warn!(dir = ?themes_dir, error = %e, "could not create themes dir");
        return;
    }

    for (name, content) in BUNDLED_THEMES {
        write_generated(
            &themes_dir.join(name),
            &format!("{BUILT_IN_THEME_HEADER}{content}"),
            false,
        );
    }

    let Ok(entries) = std::fs::read_dir(themes_dir) else {
        return;
    };
    for path in entries.filter_map(|e| e.ok()).map(|e| e.path()) {
        let Some(name) = path.file_name().and_then(|n| n.to_str()) else {
            continue;
        };
        if !name.ends_with(".css") || BUNDLED_THEMES.iter().any(|(n, _)| *n == name) {
            continue;
        }
        let built_in = !is_symlink(&path)
            && std::fs::read_to_string(&path)
                .is_ok_and(|css| css.starts_with(BUILT_IN_THEME_HEADER));
        if built_in {
            if let Err(e) = std::fs::remove_file(&path) {
                warn!(?path, error = %e, "could not remove a retired built-in theme");
            }
        }
    }
}

/// Whether `name` can be a theme's file stem or a `--css-variable` suffix:
/// letters, digits, `-` and `_` only, so it can neither leave the themes
/// directory nor end a CSS declaration.
pub fn is_safe_css_name(name: &str) -> bool {
    !name.is_empty()
        && name
            .bytes()
            .all(|b| b.is_ascii_alphanumeric() || matches!(b, b'-' | b'_'))
}

/// The stylesheet a client asked for by its path under the app's origin —
/// `themes/<name>.css` or `custom.css` — as both transports serve it: the
/// user's file in the config dir first, so a theme of theirs shadows a
/// built-in of the same name, else the bundled copy of a built-in theme. A
/// missing `custom.css` is an empty sheet, so the page never has a failed
/// request for the file most users never write. `None` is a path that is not
/// one of these.
pub fn resolve_user_css(path: &str) -> Option<Vec<u8>> {
    resolve_user_css_in(&Layout::current().config, path)
}

pub(super) fn resolve_user_css_in(dir: &Path, path: &str) -> Option<Vec<u8>> {
    let path = path.trim_start_matches('/');
    if path == "custom.css" {
        return Some(std::fs::read(dir.join("custom.css")).unwrap_or_default());
    }
    let stem = path
        .strip_prefix("themes/")
        .and_then(|file| file.strip_suffix(".css"))
        .filter(|stem| is_safe_css_name(stem))?;
    let file = format!("{stem}.css");
    if let Ok(bytes) = std::fs::read(dir.join("themes").join(&file)) {
        return Some(bytes);
    }
    BUNDLED_THEMES
        .iter()
        .find(|(name, _)| *name == file)
        .map(|(_, content)| content.as_bytes().to_vec())
}

/// The colour modes a theme supports: `dark` when its `:root.theme-dark`
/// block declares something, `light` likewise. Every bundled theme carries a
/// `theme-light` selector, but one with an empty block has no light palette,
/// and switching to it would draw the page in the browser's defaults.
pub fn theme_modes(css: &str) -> Vec<&'static str> {
    ["dark", "light"]
        .into_iter()
        .filter(|mode| {
            css.match_indices(&format!(".theme-{mode}")).any(|(at, _)| {
                let rest = &css[at..];
                let Some(open) = rest.find('{') else {
                    return false;
                };
                let body = &rest[open + 1..];
                let close = body.find('}').unwrap_or(body.len());
                body[..close].contains("--")
            })
        })
        .collect()
}

/// The mirrored scripts' directory: the data dir's `bin/`. The in-config
/// `run-shell "bash $TMUXY_DATA_DIR/bin/tmuxy/nav …"` calls and the
/// `tmuxy <subcommand>` shell wrapper reach them there, independent of the
/// .app bundle's working directory.
pub fn bin_dir() -> PathBuf {
    Layout::current().bin()
}

/// The line put under a mirrored script's shebang: the mark that the copy is
/// generated, beside its read-only mode.
const GENERATED_SCRIPT_LINE: &str =
    "# Generated by tmuxy and rewritten on every launch: an edit here is lost.\n";

/// A bundled script as it is mirrored: marked generated under its shebang.
fn mirrored_script(content: &str) -> String {
    match content.split_once('\n') {
        Some((shebang, rest)) if shebang.starts_with("#!") => {
            format!("{shebang}\n{GENERATED_SCRIPT_LINE}{rest}")
        }
        _ => content.to_string(),
    }
}

/// Mirror the bundled CLI dispatcher and helper scripts to the data dir's
/// `bin/`. Rewritten on every launch — these are not user-editable; upgrades
/// must ship their own helpers without leaving stale copies behind. Returns
/// the bin directory path.
pub fn ensure_bin_scripts() -> PathBuf {
    ensure_bin_scripts_in(&Layout::current())
}

pub(super) fn ensure_bin_scripts_in(layout: &Layout) -> PathBuf {
    let bin = layout.bin();
    if let Err(e) = std::fs::create_dir_all(bin.join("tmuxy")) {
        warn!(dir = ?bin, error = %e, "could not create bin/tmuxy dir");
        return bin;
    }
    for (rel_path, content) in BUNDLED_BIN_SCRIPTS {
        write_generated(&bin.join(rel_path), &mirrored_script(content), true);
    }
    bin
}

/// Every theme the menu offers: the built-ins and the user's own (file stems
/// of `*.css` under the config dir's `themes/`), a name once even when the
/// user's file shadows a built-in. Sorted alphabetically with `default`
/// first.
pub fn list_themes() -> Vec<String> {
    list_themes_in(&Layout::current().user_themes())
}

pub(super) fn list_themes_in(user_themes: &Path) -> Vec<String> {
    let user = std::fs::read_dir(user_themes)
        .into_iter()
        .flatten()
        .filter_map(|e| e.ok())
        .filter_map(|e| {
            let path = e.path();
            if path.extension().and_then(|s| s.to_str()) != Some("css") {
                return None;
            }
            path.file_stem()
                .and_then(|s| s.to_str())
                .filter(|s| is_safe_css_name(s))
                .map(str::to_string)
        });
    let mut names: Vec<String> = BUNDLED_THEMES
        .iter()
        .filter_map(|(name, _)| name.strip_suffix(".css").map(str::to_string))
        .chain(user)
        .collect();

    names.sort_by(|a, b| match (a.as_str(), b.as_str()) {
        ("default", "default") => std::cmp::Ordering::Equal,
        ("default", _) => std::cmp::Ordering::Less,
        (_, "default") => std::cmp::Ordering::Greater,
        _ => a.cmp(b),
    });
    names.dedup();
    names
}
